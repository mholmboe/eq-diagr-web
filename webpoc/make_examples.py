"""Write web/sed-examples.js and web/predom-examples.js for sed.html and predom.html.

Usage: python3 -I make_examples.py <SpanaDatabase project dir> <output web dir>

The examples are the SED and Predom inputs made and checked in this project
(phosphate and carbonate fractions and log concentrations, the virtual
titration of H3PO4 with NaOH, and the Fe Pourbaix and log[Fe]-pH diagrams).
"""
import json
import os
import sys

root, out_dir = sys.argv[1], sys.argv[2]

SED_EXAMPLES = [
    ("H3PO4_fract", "0.1 M H3PO4: fractions vs. pH", "results/H3PO4_0.1M/H3PO4_fract.dat", "-n=100"),
    ("H3PO4_log", "0.1 M H3PO4: log concentrations vs. pH", "results/H3PO4_0.1M/H3PO4_log.dat", "-n=100"),
    ("titration_SED", "Titration of 0.1 M H3PO4 with NaOH: pH vs. added OH-", "results/H3PO4_titration/titration_SED.dat", "-n=200"),
    ("CO3_fract", "0.01 M carbonate: fractions vs. pH", "test-runs/sed-carbonate/CO3_fract.dat", "-n=100"),
    ("CO3_log", "0.01 M carbonate: log concentrations vs. pH", "test-runs/sed-carbonate/CO3_log.dat", "-n=100"),
    ("CO3_log_Davies", "0.01 M carbonate, activity coefficients (Davies), I calculated", "test-runs/sed-carbonate/CO3_log.dat", "-n=100 -i=-1 -t=25 -m=0"),
]

PREDOM_EXAMPLES = [
    ("Fe_Eh-pH", "Fe (1 \u00b5M): Eh vs. pH (Pourbaix diagram)", "test-runs/predom-fe/Fe_Eh-pH.dat", "-n=100"),
    ("Fe_Eh-pH_aqu", "Fe: Eh vs. pH, aqueous species only, neutral pH at 60 \u00b0C", "test-runs/predom-fe/Fe_Eh-pH.dat", "-n=100 -aqu -ph -t=60"),
    ("Fe_noHaem", "Fe: Eh vs. pH without haematite (goethite instead)", "test-runs/modify/Fe_noHaem.dat", "-n=100"),
    ("Fe_logFe-pH", "Fe: log[Fe]tot vs. pH at pe 5", "test-runs/predom-fe/Fe_logFe-pH.dat", "-n=100"),
]


def write(examples, var, filename):
    items = []
    for name, title, rel, args in examples:
        with open(os.path.join(root, rel), encoding="utf-8") as f:
            items.append({"name": name, "title": title, "dat": f.read(), "args": args})
    with open(os.path.join(out_dir, filename), "w", encoding="utf-8") as f:
        f.write("// Generated by make_examples.py\n")
        f.write("window.%s = " % var + json.dumps(items, indent=1) + ";\n")


write(SED_EXAMPLES, "sedExamples", "sed-examples.js")
write(PREDOM_EXAMPLES, "predomExamples", "predom-examples.js")
