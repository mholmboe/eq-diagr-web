"""Write web/tests-data.js with the EC regression cases from eq-diagr/EC/tests.

Usage: python3 -I make_testdata.py <eq-diagr/EC/tests> <output tests-data.js>

The options are the ones the reference outputs were made with (see test-cli.sh).
"""
import json
import os
import sys

tests_dir, out_path = sys.argv[1], sys.argv[2]

CASES = [
    ("Davies_eqn", "Fe", "-m=0 -t=25 -i=-1"),
    ("Davies_eqn", "CO3-Ca-NaCl", "-m=0 -t=25 -i=-1 -tol=1e-9 -tolA=1e-8"),
    ("SIT", "CaSO4-Na-Cl", "-m=1 -t=25 -i=-1 -tol=1e-6"),
]


def read(*parts):
    path = os.path.join(tests_dir, *parts)
    return open(path, encoding="utf-8").read() if os.path.exists(path) else ""


tests = []
for d, name, opts in CASES:
    tests.append({
        "dir": d, "name": name, "options": opts,
        "dat": read(d, name + ".dat"),
        "sit": read(d, "SIT-coefficients.dta"),
        "refCsv": read(d, name + ".csv"),
    })

with open(out_path, "w", encoding="utf-8") as f:
    f.write("// Generated by make_testdata.py from eq-diagr/EC/tests\n")
    f.write("window.ecTests = " + json.dumps(tests, indent=1) + ";\n")
